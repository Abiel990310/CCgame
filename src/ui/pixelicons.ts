/** Pixels as one path of row runs, so a sprite is a handful of elements rather than hundreds. */
function runs(on: (x: number, y: number) => boolean): string {
  let d = '';
  for (let y = 0; y < N; y++) {
    for (let x = 0; x < N; ) {
      if (!on(x, y)) {
        x++;
        continue;
      }
      let end = x;
      while (end < N && on(end, y)) end++;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  }
  return d;
}

const cache = new Map<IconName, string>();

/**
 * The sprite as an SVG group on the 24-unit icon box. Layers, bottom up: the
 * outline, the body in `currentColor`, its shade and light, then the colours,
 * which cover the one-colour body wherever the CSS lets them show.
 */
export function pixelIcon(name: IconName): string {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = ART[name];
  const at = (x: number, y: number): string => (x < 0 || y < 0 || x >= N || y >= N ? '.' : rows[y][x]);
  const tone = (x: number, y: number): Tone | null => {
    const ch = at(x, y);
    return ch === '.' ? null : INK[ch][1];
  };
  const body = (x: number, y: number): boolean => {
    const t = tone(x, y);
    return t !== null && at(x, y) !== 'k' && at(x, y) !== 'x';
  };
  const edge = (x: number, y: number): boolean => {
    if (at(x, y) !== '.') return tone(x, y) === 'dark';
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (body(x + dx, y + dy)) return true;
    return false;
  };
  const layer = (cls: string, paint: string, d: string): string => (d ? `<path class="${cls}" ${paint} d="${d}"/>` : '');
  let colours = '';
  for (const [ch, [colour]] of Object.entries(INK)) {
    if (!colour) continue;
    colours += layer('c', `fill="${colour}"`, runs((x, y) => at(x, y) === ch));
  }
  const svg =
    `<g class="px" transform="scale(1.5)" shape-rendering="crispEdges" stroke="none">` +
    layer('o', 'fill="#0c0e13"', runs(edge)) +
    layer('m', 'fill="currentColor"', runs(body)) +
    layer('s', 'fill="#000" fill-opacity=".4"', runs((x, y) => body(x, y) && tone(x, y) === 'shade')) +
    layer('h', 'fill="#fff" fill-opacity=".5"', runs((x, y) => body(x, y) && tone(x, y) === 'hi')) +
    colours +
    `</g>`;
  cache.set(name, svg);
  return svg;
}
