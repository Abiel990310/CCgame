/**
 * The icon set again, drawn as 16-pixel sprites for the pixel look. Thin
 * round-capped strokes read as a website over a pixel-art scene; these share
 * the scene's grammar instead: a hard dark outline, a lit side and a shaded
 * side, and real colours for things (a leather bag, a parchment map, a red
 * heart). Each sprite also paints a one-colour version in `currentColor`, so
 * a tinted place (a gold tab, a kind-coloured card) can drop the colours and
 * keep its tint.
 *
 * Rows use one letter per pixel, and the outline is found, not drawn: any
 * empty pixel touching a painted one becomes outline, so editing a shape
 * never means redrawing its edge.
 */

